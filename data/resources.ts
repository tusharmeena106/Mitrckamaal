export function getResources(
  semesterId: number,
  subject: string,
  category: FileCategory
): Resource[] {
  return resources
    .filter(
      (r) => r.semesterId === semesterId && r.subject === subject && r.category === category
    )
    .filter((r) => r.url.trim() !== "")
    .sort((a, b) => a.label.localeCompare(b.label));
}
